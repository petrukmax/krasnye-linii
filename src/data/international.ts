export function getInternationalBlock(id: string): InternationalBlock | undefined {
  return internationalBlocks.find((b) => b.id === id);
}

export function getInternationalMaterialsByBlock(
  id: InternationalBlockId,
): InternationalMaterial[] {
  return internationalMaterials
    .filter((m) => m.blockId === id)
    .sort(
      (a, b) =>
        (a.order ?? Number.MAX_SAFE_INTEGER) - (b.order ?? Number.MAX_SAFE_INTEGER) ||
        a.date.localeCompare(b.date),
    );
}

export function getInternationalMaterial(slug: string): InternationalMaterial | undefined {
  return internationalMaterials.find((m) => m.slug === slug);
}

export function formatInternationalDate(m: InternationalMaterial): string {
  if (m.dateLabel) return m.dateLabel;
  const d = new Date(m.date + "T00:00:00Z");
  return new Intl.DateTimeFormat("ru-RU", {
    day: "numeric",
    month: "long",
    year: "numeric",
    timeZone: "UTC",
  }).format(d);
}

export function groupInternationalMaterialsByPart(
  items: InternationalMaterial[],
): { part?: string; items: InternationalMaterial[] }[] {
  const groups: { part?: string; items: InternationalMaterial[] }[] = [];
  for (const item of items) {
    const last = groups[groups.length - 1];
    if (last && last.part === item.part) {
      last.items.push(item);
    } else {
      groups.push(item.part ? { part: item.part, items: [item] } : { items: [item] });
    }
  }
  return groups;
}
