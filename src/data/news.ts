export function getNewsBlock(id: string): NewsBlock | undefined {
  return newsBlocks.find((b) => b.id === id);
}

export function getNewsMaterialsByBlock(id: NewsYear): NewsMaterial[] {
  return newsMaterials
    .filter((m) => m.year === id)
    .sort((a, b) => b.date.localeCompare(a.date));
}

export function getNewsMaterial(slug: string): NewsMaterial | undefined {
  return newsMaterials.find((m) => m.slug === slug);
}

export function detectNewsBlockByDate(date: string): NewsYear {
  return date >= "2026-01-01" ? "2026" : "2025";
}

export function formatNewsDate(m: NewsMaterial): string {
  if (m.dateLabel) return m.dateLabel;
  const d = new Date(m.date + "T00:00:00Z");
  return new Intl.DateTimeFormat("ru-RU", {
    day: "numeric",
    month: "long",
    year: "numeric",
    timeZone: "UTC",
  }).format(d);
}
